import { BRANCHES } from './data/branches/index.js';
import { DENSITIES, SCALES } from './data/pools.js';
import type { Branch, BranchFamily } from './types.js';

/** One-line-per-branch catalogue (Markdown table). */
export function renderBranchList(opts: { family?: BranchFamily } = {}): string {
  const list = opts.family ? BRANCHES.filter((b) => b.family === opts.family) : BRANCHES;
  const out = [
    `${list.length} branches${opts.family ? ` in family "${opts.family}"` : ''} (library order = mapping order)`,
    '',
    '| # | id | 中文 | English | family | keywords |',
    '|---|---|---|---|---|---|',
  ];
  for (const b of list) {
    const idx = BRANCHES.indexOf(b);
    out.push(
      `| ${idx} | \`${b.id}\` | ${b.name.zh} | ${b.name.en} | ${b.family} | ${b.keywords.slice(0, 4).join(' · ')} |`,
    );
  }
  return out.join('\n');
}

/** Full Markdown description of one branch with every option. */
export function renderBranch(b: Branch): string {
  const out: string[] = [];
  out.push(`# ${b.name.zh} · ${b.name.en} (\`${b.id}\`)`);
  out.push('');
  out.push(`family: **${b.family}** · library index ${BRANCHES.indexOf(b)}`);
  out.push('');
  out.push(`> ${b.concept.zh}`);
  out.push('>');
  out.push(`> ${b.concept.en}`);
  out.push('');
  out.push(`**References:** ${b.references.join('; ')}`);
  out.push('');
  out.push(`**Keywords:** ${b.keywords.join(' · ')}`);
  out.push('');
  out.push('## Tokens');
  out.push('');
  out.push(`- grid: ${b.tokens.grid}`);
  out.push(`- radius: ${b.tokens.radius}`);
  out.push(`- border: ${b.tokens.border}`);
  out.push(`- shadow: ${b.tokens.shadow}`);
  out.push('');
  out.push('## Layouts (byte 3)');
  for (const l of b.layouts) {
    out.push('');
    out.push(`### ${l.name} (\`${l.id}\`)`);
    out.push(l.description);
    out.push(`- grid: ${l.grid}`);
    l.structure.forEach((s, i) => out.push(`${i + 1}. ${s}`));
  }
  out.push('');
  out.push('## Type (byte 4)');
  out.push('');
  for (const t of b.type) {
    const mono = t.mono ? ` · mono ${t.mono.family}` : '';
    out.push(
      `- **${t.name}** (\`${t.id}\`): display ${t.display.family} ${t.display.weights.join('/')} · body ${t.body.family} ${t.body.weights.join('/')}${mono} · CJK ${t.cjk.display} / ${t.cjk.body} — ${t.notes}`,
    );
  }
  out.push('');
  out.push('## Palettes (byte 5)');
  out.push('');
  for (const p of b.palettes) {
    const c = p.colors;
    out.push(
      `- **${p.name}** (\`${p.id}\`): paper \`${c.paper}\` ink \`${c.ink}\` muted \`${c.muted}\` accent \`${c.accent}\` accent2 \`${c.accent2}\` rule \`${c.rule}\` panel \`${c.panel}\` — ${p.usage}`,
    );
  }
  out.push('');
  out.push(`## Density (byte 6): ${b.densities.map((d) => `${d} (${DENSITIES[d].name.zh})`).join(' · ')}`);
  out.push('');
  out.push('## Motion (byte 7)');
  out.push('');
  for (const m of b.motion)
    out.push(
      `- **${m.name}** (\`${m.id}\`, ${m.duration} ${m.easing}): ${m.description} Reduced: ${m.reduced}`,
    );
  out.push('');
  out.push('## Motifs (byte 8)');
  out.push('');
  for (const m of b.motifs) out.push(`- **${m.name}** (\`${m.id}\`): ${m.description}`);
  out.push('');
  out.push('## Anchors (byte 9)');
  out.push('');
  for (const m of b.anchors) out.push(`- **${m.name}** (\`${m.id}\`): ${m.description}`);
  out.push('');
  out.push(`## Scale (byte 10): ${b.scales.map((s) => SCALES[s].name).join(' · ')}`);
  out.push('');
  out.push('## Surfaces (byte 11)');
  out.push('');
  for (const s of b.surfaces)
    out.push(`- **${s.name}** (\`${s.id}\`): ${s.description}${s.css ? ` — \`${s.css}\`` : ''}`);
  out.push('');
  out.push('## Must');
  out.push('');
  for (const m of b.must) out.push(`- ${m}`);
  out.push('');
  out.push('## Must not');
  out.push('');
  for (const m of b.mustNot) out.push(`- ${m}`);
  return out.join('\n');
}

const FAMILY_ZH: Record<BranchFamily, string> = {
  print: '印刷品',
  document: '文档/票据',
  signage: '标识/招牌',
  screen: '屏幕/仪器',
  craft: '手作/东方',
  modernist: '现代主义',
};

/** Compact catalogue of the whole library for docs/branches.md (generated, do not edit by hand). */
export function renderBranchCatalog(): string {
  const out: string[] = [];
  out.push('<!-- GENERATED by `npm run sync` from packages/core/src/data — do not edit by hand -->');
  out.push('');
  out.push(`# 分支库 Branch library (${BRANCHES.length})`);
  out.push('');
  out.push(
    '每个分支都是一个真实世界的设计门类，带完整 token。哈希的第 0–1 字节选分支，第 3–11 字节在分支内选具体选项。顺序即映射顺序。',
  );
  out.push('');
  out.push(renderBranchList());
  out.push('');
  for (const b of BRANCHES) {
    out.push(`## ${BRANCHES.indexOf(b)}. ${b.name.zh} · ${b.name.en} — \`${b.id}\``);
    out.push('');
    out.push(`*${FAMILY_ZH[b.family]} / ${b.family}* — ${b.concept.zh}`);
    out.push('');
    out.push(`- **参考 References:** ${b.references.join('; ')}`);
    out.push(`- **字体 Type:** ${b.type.map((t) => `${t.display.family} + ${t.body.family}`).join(' · ')}`);
    out.push(
      `- **配色 Palettes:** ${b.palettes.map((p) => `${p.name} (\`${p.colors.paper}\` \`${p.colors.ink}\` \`${p.colors.accent}\`)`).join(' · ')}`,
    );
    out.push(`- **版式 Layouts:** ${b.layouts.map((l) => l.name).join(' · ')}`);
    out.push(`- **首屏锚点 Anchors:** ${b.anchors.map((a) => a.name).join(' · ')}`);
    out.push(`- **Tokens:** radius — ${b.tokens.radius} / shadow — ${b.tokens.shadow}`);
    out.push('');
  }
  return out.join('\n');
}
